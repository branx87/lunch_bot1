# ##time_config.py
from datetime import time, timedelta, date
import pytz

class TimeConfig:
    """Централизованная конфигурация временных настроек бота"""
    
    # Часовой пояс
    TIMEZONE = pytz.timezone('Europe/Moscow')
    
    # --- Старый поставщик (до 26.10.2026) ---
    # Время приема заказов
    ORDER_DEADLINE = time(9, 30)  # До скольки принимаются заказы
    
    # Время для изменений/отмен
    MODIFICATION_DEADLINE = time(9, 30)  # До скольки можно изменять/отменять
    
    # --- Новый поставщик питания «Благовар» (с 26.10.2026) ---
    # Заявки принимаются заранее: на понедельник заказ делается в пятницу до 15:00,
    # на вторник — в понедельник до 15:00 и т.д. Заказ на сегодня не принимается.
    NEW_SUPPLIER_START_DATE = date(2026, 10, 26)
    ADVANCE_ORDER_DEADLINE = time(15, 0)  # Крайний срок заказа на следующий рабочий день
    ADVANCE_MODIFICATION_DEADLINE = time(15, 0)  # Изменение/отмена — до этого же момента
    
    # Время немедленной синхронизации (для заказов на сегодня после этого времени)
    IMMEDIATE_SYNC_TIME = time(9, 25)
    
    # Выходные дни (0=понедельник, 6=воскресенье)
    WEEKEND_DAYS = [5, 6]  # Суббота, воскресенье
    
    # Время для cron-задач
    MORNING_REMINDER_TIME = time(9, 0)    # Напоминания в 9:00
    # Отчёт за СЕГОДНЯ — в день обеда, заказ на сегодня сделан накануне
    TODAY_REPORTS_TIME = time(9, 31)      # Отчёт «на сегодня» в 9:31
    # Отчёт за ЗАВТРА (следующий рабочий день) — после закрытия окна заказов в 15:00
    TOMORROW_REPORTS_TIME = time(15, 5)   # Отчёт «на завтра» в 15:05
    ACCOUNTING_REPORT_TIME = time(11, 0)  # Бухгалтерский отчет в 11:00
    SYNC_EMPLOYEES_TIME = time(18, 0)     # Синхронизация в 18:00

    # Выгрузка заказов в Bitrix24 для учёта — в день обеда, как раньше.
    # Не путать с окном приёма заказов (15:00 предыдущего рабочего дня).
    BITRIX_PUSH_TIME = time(9, 30)        # Выгрузка в Bitrix в 9:21 и 9:29:50

    # Синхронизация заказов из Bitrix24.
    # Импорт заказов из формы отключён (флаг accept_bitrix_form_orders),
    # а свои заказы бот привязывает к Bitrix ID сразу при выгрузке.
    # Осталась одна функция — подхватывать ручные правки в Bitrix24
    # (отмена, изменение количества), поэтому частая синхронизация
    # не нужна: раз в час + две сверки перед отчётами.
    BITRIX_SYNC_ENABLED = True            # Часовая сверка заказов
    BITRIX_SYNC_CRON_MINUTE = 0
    BITRIX_SYNC_CRON_HOURS = '8-16'
    # Сверка перед отчётами (час, минута) — чтобы отчёт был по свежим данным
    BITRIX_SYNC_BEFORE_REPORTS = ((9, 25), (15, 0))
    
    # Дни для cron-задач (0=понедельник, 6=воскресенье)
    WORK_DAYS = [0, 1, 2, 3, 4]  # Пн-Пт

    MAX_PORTIONS = 5  # Максимальное количество порций в заказе

# Создаем глобальный экземпляр для импорта
TIME_CONFIG = TimeConfig()